/**
 * Strict SSRF guard for FlowStudio PWA Colab T4 tunnel proxy.
 * ONLY permits HTTPS URLs hosted on Cloudflare's free ephemeral tunnel domain (*.trycloudflare.com)
 * with no embedded credentials, non-standard ports, private IPs, or path traversal.
 */

const TRYCLOUDFLARE_HOST_RE = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.trycloudflare\.com$/i;

const ALLOWED_PATHS = [
  /^\/api\/health$/,
  /^\/api\/image$/,
  /^\/api\/video$/,
  /^\/api\/job\/[a-zA-Z0-9_-]{4,64}$/,
  /^\/outputs\/[a-zA-Z0-9._-]{3,128}$/,
];

export function validateColabBaseUrl(rawUrl) {
  if (typeof rawUrl !== 'string' || !rawUrl.trim()) {
    return { ok: false, error: 'Missing Colab tunnel URL.' };
  }

  let parsed;
  try {
    parsed = new URL(rawUrl.trim());
  } catch {
    return { ok: false, error: 'Invalid URL format.' };
  }

  if (parsed.protocol !== 'https:') {
    return { ok: false, error: 'Only HTTPS tunnel URLs are allowed.' };
  }
  if (parsed.username || parsed.password) {
    return { ok: false, error: 'URL credentials are forbidden.' };
  }
  if (parsed.port && parsed.port !== '443') {
    return { ok: false, error: 'Non-standard ports are forbidden.' };
  }
  if (!TRYCLOUDFLARE_HOST_RE.test(parsed.hostname)) {
    return {
      ok: false,
      error: 'Host must be a valid *.trycloudflare.com tunnel generated by the Colab T4 notebook.',
    };
  }

  return { ok: true, origin: `https://${parsed.hostname}` };
}

export function validateColabPath(rawPath) {
  if (typeof rawPath !== 'string' || !rawPath.startsWith('/')) {
    return { ok: false, error: 'Invalid backend path.' };
  }
  if (rawPath.includes('..') || rawPath.includes('\\') || rawPath.includes('?') || rawPath.includes('#')) {
    return { ok: false, error: 'Path traversal or query injection is forbidden.' };
  }
  const matched = ALLOWED_PATHS.some((re) => re.test(rawPath));
  if (!matched) {
    return { ok: false, error: `Disallowed Colab endpoint path: ${rawPath}` };
  }
  return { ok: true, path: rawPath };
}

export function setCorsHeaders(res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Cache-Control', 'no-store');
}
